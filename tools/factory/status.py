"""Compute the four STATE.md fields from the issue files (SPEC.md §6, issue 190).

`/factory-status` used to ask a model to read every issue frontmatter and pick the last completed
and next-up issues by hand. This script does that calculation in code instead. It follows the same
rules as `lastCompleted` and `nextIssue` in tools/console/src/parse.mjs, and
tools/factory/tests/test_status.py proves the two agree on the fixture repo.

Usage:
    python -m tools.factory.status                 print the four fields, write nothing
    python -m tools.factory.status --write         also write docs/factory/STATE.md, and only that
    python -m tools.factory.status --root DIR      read DIR's issues and git state (default: this checkout)
    python -m tools.factory.status --issues DIR    read issue files from DIR instead

Data faults are printed first, one `FAULT:` line each: a done issue with `commit: null`, an open
issue whose `depends_on` names a missing issue, and a frontmatter block that does not parse. The
script reports them and does not fix them; the human decides.

Exit code: 0 when it ran, 2 when the issue directory does not exist.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
ISSUES_REL = Path("docs/factory/issues")
STATE_REL = Path("docs/factory/STATE.md")
STATE_HEADER = "<!-- Regenerated by /factory-status from docs/factory/issues/. If the two disagree, the issues win. -->"
SIDE = {"Side", "Post-M6"}
LABEL_WIDTH = 17
WRAP_WIDTH = 100

FILE_RE = re.compile(r"^\d+-.*\.md$")
FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---", re.DOTALL)


@dataclass
class Issue:
    n: int
    file: str
    title: str
    milestone: str
    status: str  # done | in-progress | open
    depends_on: list[int]
    commit: str | None


def load_issues(issues_dir: Path) -> tuple[list[Issue], list[str]]:
    """Every issue file under `issues_dir`, sorted by number, plus any file that could not be read.

    The filter and the status mapping match tools/console/src/parse.mjs `parseIssues`."""
    issues: list[Issue] = []
    faults: list[str] = []
    for path in sorted(issues_dir.glob("*.md")):
        if not FILE_RE.match(path.name) or path.name.endswith("-test-cases.md"):
            continue
        match = FRONTMATTER_RE.match(path.read_text(encoding="utf-8"))
        if not match:
            continue
        try:
            fm = yaml.safe_load(match.group(1)) or {}
            if not isinstance(fm, dict) or fm.get("issue") is None:
                continue
            deps = fm.get("depends_on")
            commit = fm.get("commit")
            issues.append(
                Issue(
                    n=int(fm["issue"]),
                    file=path.name,
                    title=str(fm.get("title") or ""),
                    milestone=str(fm.get("milestone") or ""),
                    status=_status(fm.get("status")),
                    depends_on=[int(d) for d in deps] if isinstance(deps, list) else [],
                    commit=None if commit is None else str(commit),
                )
            )
        except (yaml.YAMLError, ValueError, TypeError):
            faults.append(f"{path.name} has frontmatter that does not parse")
    issues.sort(key=lambda i: i.n)
    return issues, faults


def _status(value: object) -> str:
    if value == "done":
        return "done"
    if value == "in-progress":
        return "in-progress"
    return "open"


def last_completed(issues: list[Issue]) -> Issue | None:
    done = [i for i in issues if i.status == "done"]
    return done[-1] if done else None


def next_issue(issues: list[Issue]) -> Issue | None:
    """Lowest open main-line issue whose every dependency is done. Mirrors parse.mjs `nextIssue`."""
    done = {i.n for i in issues if i.status == "done"}
    for i in issues:
        if i.status == "open" and i.milestone not in SIDE and all(d in done for d in i.depends_on):
            return i
    return None


def data_faults(issues: list[Issue]) -> list[str]:
    known = {i.n for i in issues}
    out: list[str] = []
    for i in issues:
        if i.status == "done" and i.commit is None:
            out.append(f"done #{i.n} has commit: null ({i.file})")
    for i in issues:
        if i.status != "open":
            continue
        for dep in i.depends_on:
            if dep not in known:
                out.append(f"open #{i.n} depends_on #{dep}, and no such issue exists ({i.file})")
    return out


def _git(root: Path, *args: str) -> str | None:
    """stdout of one git command run in `root`, or None when it fails or git is missing.

    `--no-optional-locks` is passed by the caller where it matters, so a status read never
    refreshes the index."""
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=root,
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=False,
        )
    except OSError:
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def branch_line(root: Path) -> str:
    """`<branch>, <remote>, <n> files dirty, gate stamp for <sha7>` as the STATE.md layout reads."""
    branch = _git(root, "branch", "--show-current")
    if branch is None:
        branch_part = "no git checkout"
    else:
        branch_part = branch or "detached HEAD"

    remote_text = _git(root, "remote", "-v") or ""
    urls: list[str] = []
    for line in remote_text.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[-1] == "(fetch)" and parts[1] not in urls:
            urls.append(parts[1])
    remote_part = ", ".join(urls) if urls else "no remote"

    porcelain = _git(root, "--no-optional-locks", "status", "--porcelain")
    dirty = len(porcelain.splitlines()) if porcelain else 0
    dirty_part = f"{dirty} files dirty"

    head = _git(root, "rev-parse", "HEAD")
    if head is None:
        stamp_part = "no commit, no gate stamp"
    else:
        common = _git(root, "rev-parse", "--path-format=absolute", "--git-common-dir")
        stamped = bool(common) and (Path(common) / "verstaan-gate-stamps" / head).exists()
        stamp_part = f"{'gate stamp' if stamped else 'no gate stamp'} for {head[:7]}"

    return f"{branch_part}, {remote_part}, {dirty_part}, {stamp_part}"


def render_fields(fields: list[tuple[str, str]]) -> str:
    lines: list[str] = []
    for label, value in fields:
        lines.append(
            textwrap.fill(
                value,
                width=WRAP_WIDTH,
                initial_indent=f"{label:<{LABEL_WIDTH}}",
                subsequent_indent=" " * LABEL_WIDTH,
                break_long_words=False,
                break_on_hyphens=False,
            )
        )
    return "\n".join(lines)


def build_fields(issues: list[Issue], root: Path) -> list[tuple[str, str]]:
    last = last_completed(issues)
    nxt = next_issue(issues)
    if last is None:
        last_text = "none"
    else:
        last_text = f"#{last.n} — {last.title} ({last.milestone}), commit {last.commit or 'null'}"
    if nxt is None:
        next_text = "none, no open quest has every dependency done"
        resume_text = "none"
    else:
        next_text = f"#{nxt.n} — {nxt.title} ({nxt.milestone})"
        resume_text = f"/factory-run {nxt.n:02d}"
    return [
        ("Last completed:", last_text),
        ("Next up:", next_text),
        ("Branch / PR:", branch_line(root)),
        ("Resume with:", resume_text),
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--write", action="store_true", help="also write docs/factory/STATE.md under --root"
    )
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="checkout to read; defaults to this checkout"
    )
    parser.add_argument(
        "--issues",
        type=Path,
        default=None,
        help="issue directory; defaults to <root>/docs/factory/issues",
    )
    args = parser.parse_args(argv)

    reconfigure = getattr(sys.stdout, "reconfigure", None)
    if callable(reconfigure):
        reconfigure(encoding="utf-8")

    root = args.root.resolve()
    issues_dir = (args.issues or root / ISSUES_REL).resolve()
    if not issues_dir.is_dir():
        print(f"status: no issue directory at {issues_dir}", file=sys.stderr)
        return 2

    issues, read_faults = load_issues(issues_dir)
    faults = read_faults + data_faults(issues)
    body = render_fields(build_fields(issues, root))

    out: list[str] = [f"FAULT: {line}" for line in faults]
    if out:
        out.append("")
    out.append(body)
    sys.stdout.write("\n".join(out) + "\n")

    if args.write:
        state = root / STATE_REL
        state.write_text(f"{STATE_HEADER}\n\n{body}\n", encoding="utf-8", newline="\n")
        print(f"wrote {state.relative_to(root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
